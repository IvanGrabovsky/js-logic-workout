/**
 * ==============================================================================
 * МОДУЛЬ 1: ВВЕДЕННЯ/ВИВЕДЕННЯ (alert/prompt), МЕТОДИ РЯДКІВ (trim), ЗМІННІ ТА ТИПИ
 * ==============================================================================
 *
 * 📖 ТЕОРІЯ:
 *
 * 1. prompt(message, [default]):
 *    - Запитує користувача ввести текст у модальному вікні браузера.
 *    - ⚠️ ЗАВЖДИ повертає рядок (string), навіть якщо користувач ввів цифри ("42")!
 *    - Якщо користувач натиснув "Скасувати" (Cancel) або Esc — повертає null!
 *    - Якщо натиснув "ОК" без введення тексту — повертає порожній рядок "".
 *
 * 2. alert(message):
 *    - Відображає інформаційне повідомлення користувачеві.
 *    - Повертає undefined.
 *
 * 3. confirm(question):
 *    - Відображає вікно з кнопками "ОК" (true) та "Скасувати" (false).
 *
 * 4. МЕТОД .trim() ТА ОЧИЩЕННЯ РЯДКІВ:
 *    - Користувачі часто випадково ставлять пробіли на початку чи в кінці ("  Тарас  ", " 17 ").
 *    - str.trim(): видаляє пробіли, символи табуляції (\t) та перенесення рядків (\n)
 *      з ОБОХ кінців рядка. Повертає новий рядок, оригінал НЕ змінює!
 *      Приклад: "   привіт  ".trim() === "привіт"
 *      Приклад: "    ".trim() === "" (зручно для перевірки, чи рядок не порожній!)
 *    - str.trimStart(): видаляє пробіли тільки на початку.
 *    - str.trimEnd(): видаляє пробіли тільки в кінці.
 *    - str.toLowerCase() / str.toUpperCase(): переводить рядок у нижній/верхній регістр.
 *
 * 5. Оголошення змінних:
 *    - const: за замовчуванням (значення не переприсвоюється).
 *    - let: тільки якщо значення буде перезаписуватись.
 *    - var: застаріле, не використовуємо!
 *
 * 6. Інкремент / декремент (++, --) та вирази присвоєння (+=, -=):
 *    - n++ (постфіксний): повертає поточне значення, після чого збільшує n на 1.
 *    - ++n (префіксний): спершу збільшує n на 1, потім повертає оновлене значення.
 *    - n += 5 еквівалентно n = n + 5 (працює також для -=, *=, /=).
 *
 * 7. Об'єкти (Object) — швидкий старт:
 *    - Об'єкт об'єднує кілька властивостей у форматі { ключ: значення }.
 *    - Створення: const person = { name: 'Тарас', age: 17 };
 *    - Звернення до поля: person.name або person['name'].
 *    - Повернення з функції: return { success: true, count: 5 };
 */

